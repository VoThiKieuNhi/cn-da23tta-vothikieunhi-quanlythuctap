router.post('/reports',reportUpload,reports.studentWrite);
router.put('/reports/:id',reportUpload,reports.studentWrite);
router.delete('/reports/:id',reports.studentWrite);
router.get('/reports/:id/download',reports.download);
const progress=require('../controllers/progressController');
router.get('/progress',progress.studentList);
